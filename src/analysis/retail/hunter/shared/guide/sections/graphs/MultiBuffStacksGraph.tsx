import Analyzer from 'parser/core/Analyzer';
import { VisualizationSpec } from 'react-vega';
import BaseChart, { formatTime } from 'parser/ui/BaseChart';
import AutoSizer from 'react-virtualized-auto-sizer';
import BuffStackTracker from 'parser/shared/modules/BuffStackTracker';

/**
 * Represents a single data point in the graph's series.
 */
interface SeriesPoint {
  name: string;
  timestamp: number;
  amount: number;
  type: 'buff';
}

/**
 * Defines the specification for a single series (a single buff) to be plotted on the graph.
 */
interface SeriesSpec {
  /** The name of the buff series, used in the legend and tooltips. */
  name: string;
  /** The color of the series on the graph, in hex format (e.g., '#ff0000'). */
  color: string;
  /** The BuffStackTracker instance that contains the parsed data for this buff. */
  tracker: BuffStackTracker;
}

/**
 * An abstract implementation for producing a graph that shows the number of stacks for multiple
 * buffs over the course of an encounter.
 *
 * The output is a React component (a div) generated by the {@link plot} field. This component
 * is not automatically rendered; it must be added to a statistic or panel by the implementing module.
 *
 * Buffs to be graphed are specified by implementing the {@link series} function, which should
 * return an array of SeriesSpec objects.
 */
export default abstract class MultiBuffStacksGraph extends Analyzer {
  /**
   * Implement this method to define the buffs that should be plotted on the graph.
   * This should return an array of `SeriesSpec` objects, each defining a buff's
   * name, color, and its associated `BuffStackTracker`.
   */
  abstract series(): SeriesSpec[];

  /**
   * Processes the raw buff stack data from the trackers into a "dense" flat array of `SeriesPoint`
   * objects that can be consumed by Vega-Lite. "Dense" data means that at any timestamp where any
   * buff changes, we generate a data point for *every* buff being tracked. This ensures that
   * tooltips always have complete data and prevents aggregation errors.
   */
  private buildSeries(): SeriesPoint[] {
    const seriesSpecs = this.series();
    if (seriesSpecs.length === 0) {
      return [];
    }

    // 1. Get all unique timestamps where any buff changes.
    const uniqueTimestamps = new Set<number>([this.owner.fight.start_time]);
    seriesSpecs.forEach((s) =>
      s.tracker.buffStackUpdates.forEach((u) => uniqueTimestamps.add(u.timestamp)),
    );
    const sortedTimestamps = Array.from(uniqueTimestamps).sort((a, b) => a - b);

    // Add the end of the fight to ensure graphs extend to the finish.
    const end = this.owner.fight.end_time;
    if (sortedTimestamps[sortedTimestamps.length - 1] < end) {
      sortedTimestamps.push(end);
    }

    // 2. Create a map for quick lookup of the NEW stack value at a given timestamp.
    // Map<timestamp, Map<buffName, newStackValue>>
    const updatesByTime = new Map<number, Map<string, number>>();
    seriesSpecs.forEach((s) => {
      s.tracker.buffStackUpdates.forEach((u) => {
        if (!updatesByTime.has(u.timestamp)) {
          updatesByTime.set(u.timestamp, new Map<string, number>());
        }
        updatesByTime.get(u.timestamp)!.set(s.name, u.current);
      });
    });

    // 3. Iterate through each unique timestamp and generate a state snapshot for ALL buffs.
    const out: SeriesPoint[] = [];
    const currentStacks: Record<string, number> = {};
    seriesSpecs.forEach((s) => (currentStacks[s.name] = 0));

    for (const timestamp of sortedTimestamps) {
      // Get all updates that occurred at this specific timestamp.
      const updates = updatesByTime.get(timestamp);
      if (updates) {
        // Apply the updates to our running state.
        updates.forEach((newValue, buffName) => {
          currentStacks[buffName] = newValue;
        });
      }

      // Emit a data point for every series at this timestamp with its current value.
      // This creates "dense" data, ensuring the tooltip always has a value for every buff.
      seriesSpecs.forEach((s) => {
        out.push({
          name: s.name,
          timestamp: timestamp,
          amount: currentStacks[s.name],
          type: 'buff',
        });
      });
    }

    return out;
  }

  get plot() {
    const graphData = this.buildSeries();
    const start = this.owner.fight.start_time;
    const end = graphData.length ? Math.max(...graphData.map((d) => d.timestamp)) : start;
    const graphLength = Math.max(end - start, 0);

    // If the graph is longer than a certain threshold, we'll enable horizontal scrolling and adjust the tick count.
    const threshold = 8 * 60 * 1000;
    // If the fight is long, add a tick every 20s for readability.
    const tickCount = graphLength > threshold ? Math.floor(graphLength / 20000) : 25;
    // Calculate the width percentage to ensure the graph has a consistent scale when scrolling.
    const widthPercentage = graphLength > threshold ? (graphLength / threshold) * 100 : 100;

    const names = this.series().map((s) => s.name);
    const colors = this.series().map((s) => s.color);

    const spec: VisualizationSpec = {
      data: { name: 'graphData' },
      // These transforms apply to all data before it's passed to the layers.
      // We filter out invalid data and shift the timestamp to be relative to the fight start.
      transform: [
        { filter: 'isValid(datum.timestamp)' },
        { calculate: `datum.timestamp - ${start}`, as: 'timestamp_shifted' },
        // A human-readable time field is pre-calculated for use in the tooltip.
        { calculate: formatTime('datum.timestamp_shifted'), as: 'timestamp_humanized' },
      ],
      // Define the common x-axis for all layers.
      encoding: {
        x: {
          field: 'timestamp_shifted',
          type: 'quantitative',
          axis: { labelExpr: formatTime('datum.value'), tickCount: tickCount, grid: false },
          scale: { nice: false },
          title: null,
        },
      },
      layer: [
        // This layer renders the visible area chart and the highlight points on hover.
        {
          // Filter the data to only include our buff stack information.
          transform: [{ filter: "datum.type === 'buff'" }],
          // Define the y-axis and color scheme for the chart. These will be inherited by nested layers.
          encoding: {
            y: { field: 'amount', type: 'quantitative', title: 'Stacks' },
            color: {
              field: 'name',
              type: 'nominal',
              scale: { domain: names, range: colors },
              legend: { title: 'Buff' },
            },
          },
          layer: [
            // The main area graph.
            {
              mark: {
                type: 'area',
                line: { strokeWidth: 2 },
                opacity: 0.2,
                interpolate: 'step-after',
              },
            },
            // A layer for the highlight points that appear when hovering.
            // It inherits the y and color encoding from its parent.
            {
              transform: [{ filter: { param: 'hover', empty: false } }],
              mark: 'point',
            },
          ],
        },
        // This layer handles all user interaction, including the vertical rule and the tooltip.
        // It is self-contained and operates on a transformed version of the data.
        {
          // We need to transform the data from "long" to "wide" format for the tooltip.
          // This creates a single row for each timestamp with columns for each buff's stack count.
          transform: [
            { filter: 'datum.amount > 0' },
            {
              pivot: 'name',
              value: 'amount',
              groupby: ['timestamp_shifted', 'timestamp_humanized'],
            },
          ],
          // Use an invisible rule mark across the entire chart as the target for mouse events.
          mark: 'rule',
          // This defines the 'hover' selection, which captures the nearest timestamp to the mouse.
          params: [
            {
              name: 'hover',
              select: {
                type: 'point',
                fields: ['timestamp_shifted'],
                nearest: true,
                on: 'mouseover',
                clear: 'mouseout',
              },
            },
          ],
          // This encoding block controls the vertical rule's visibility and the tooltip content.
          encoding: {
            // This is the trick to show the vertical rule: make it transparent unless the 'hover'
            // selection is active at the current timestamp.
            opacity: {
              condition: { value: 0.8, param: 'hover', empty: false },
              value: 0,
            },
            // The tooltip is generated from the fields of the pivoted data.
            tooltip: [
              { field: 'timestamp_humanized', type: 'nominal', title: 'Time' },
              ...names.map((n) => ({ field: n, type: 'quantitative' as const, title: n })),
            ],
          },
        },
      ],
    };

    return (
      <div
        className="graph-container"
        style={{ width: '100%', overflowX: graphLength > threshold ? 'auto' : 'hidden' }}
      >
        <div
          style={{
            padding: graphLength > threshold ? '0 0 30px' : '0',
            width: `${widthPercentage}%`,
            overflowY: 'hidden',
            minHeight: 200,
          }}
        >
          <AutoSizer>
            {({ width, height }) => (
              <BaseChart
                spec={spec}
                data={{ graphData: graphData }}
                width={width}
                height={height}
              />
            )}
          </AutoSizer>
        </div>
      </div>
    );
  }
}
