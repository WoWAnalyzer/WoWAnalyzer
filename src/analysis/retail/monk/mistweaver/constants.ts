export function getCurrentRSKTalent(player: Combatant): Talent {
  return player.hasTalent(TALENTS_MONK.RUSHING_WIND_KICK_MISTWEAVER_TALENT)
    ? TALENTS_MONK.RUSHING_WIND_KICK_MISTWEAVER_TALENT
    : TALENTS_MONK.RISING_SUN_KICK_TALENT;
}
export function getCurrentRSKTalentDamage(player: Combatant): Spell {
  return player.hasTalent(TALENTS_MONK.RUSHING_WIND_KICK_MISTWEAVER_TALENT)
    ? SPELLS.RUSHING_WIND_KICK_DAMAGE
    : SPELLS.RISING_SUN_KICK_DAMAGE;
}

export function getCurrentCelestialTalent(player: Combatant): Talent {
  return player.hasTalent(TALENTS_MONK.INVOKE_YULON_THE_JADE_SERPENT_TALENT)
    ? TALENTS_MONK.INVOKE_YULON_THE_JADE_SERPENT_TALENT
    : TALENTS_MONK.INVOKE_CHI_JI_THE_RED_CRANE_TALENT;
}

export function getSelectedPrimaryHeal(player: Combatant): Talent | Spell {
  return player.hasTalent(TALENTS_MONK.SHEILUNS_GIFT_TALENT)
    ? TALENTS_MONK.SHEILUNS_GIFT_TALENT
    : SPELLS.VIVIFY;
}

export function getCurrentAncientTeachingsTransferCoefficient(player: Combatant): number {
  let coefficient = AT_TRANSFER_COEFFICIENT;

  if (player.hasTalent(TALENTS_MONK.JADEFIRE_TEACHINGS_TALENT)) {
    coefficient += JADEFIRE_TEACHINGS_TRANSFER_COEFFICIENT;
  }

  if (player.hasTalent(TALENTS_MONK.MEDITATIVE_FOCUS_TALENT)) {
    coefficient += MEDITATIVE_FOCUS_TRANSFER_COEFFICIENT;
  }

  return coefficient;
}
